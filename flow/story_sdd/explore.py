from pathlib import Path
from textwrap import dedent

import gigacode
import git


def explore(data: dict):
    repo_path = Path(data["sandbox_path"]) / "repo"

    explore_file = f"openspec/changes/explore-{data['issue_key']}.md"
    explore_path = repo_path / explore_file

    data["explore_file"] = explore_file

    prompt = dedent(f"""
        Проведи исследование кодовой базы для подготовки к спецификации по задаче.
        Действуй MUST самостоятельно, не задавая никаких вопросов.

        # Что нужно сделать
        1. Изучи описание задачи ниже.
        2. Исследуй существующую кодовую базу проекта.
        3. ОБЯЗАТЕЛЬНО найди аналогичные или похожие сервисы/модули — они станут архитектурным эталоном. 4. Проанализируй принятые в проекте конвенции: как пишется логика, какие паттерны

        # Ограничения (MUST)

        - Git-коммит НЕ делай.
        - НЕ выполняй /opsx:propose — это отдельный последующий шаг.
        - НЕ пиши код реализации — только исследование.
        - Не задавай уточняющих вопросов, решай сам на основе того, что видишь в проекте.

        # Описание задачи
        ```
        {data['jira_task']['description']}
        ```
        ## Дополнительно
        - Номер спринта: `{data['jira_task']['sprint_version']}`

        # Формат результата

        После завершения СОХРАНИ отчёт в файл {explore_file} строго в следующем формате:

        ```
        === ФОРМАТ ФАЙЛА НАЧАЛО ===
        ## Задача
        <несколько предложений, что именно делаем и для чего>

        ## Область
        - сервис: <название сервиса>
        - <конкретные файлы и модули, которые будут затронуты>

        ## Что НЕ делаем
        - <явные границы, что вне области этой задачи>

        ## Референсные файлы
        - <путь/к/файлу.kt> — <почему взят за референс, что именно из него использовать>
        - <ещё файлы, если есть>

        ## Ключевые находки по задаче
        - <что уже есть в проекте и может быть переиспользовано>
        - <какие модули будут затронуты>

        ## Открытые вопросы и риски
        - <что осталось неясным или требует внимания при реализации>
        - <если ничего — напиши "Не выявлено">

        Заполни ВСЕ секции. Если по какой-то секции нет данных — явно напиши "Не найдено"

        === ФОРМАТ ФАЙЛА КОНЕЦ ====
        ```
        """).strip()

    gigacode.run(prompt, repo_path)

    if not explore_path.exists():
        raise Exception(f"Не сформирован файл {explore_file}")
    git.commit_all(repo_path, f"explore done. {data['issue_key']} [skip ci]")
