def propose(ctx: TaskContext, change_name: str) -> str:
    return render(
        """
        /opsx:propose — подготовь спецификацию на основе проведённого исследования в `{ctx.explore_file}`

        Действуй MUST самостоятельно, не задавая никаких вопросов.

        # Обязательный контекст

        Сначала ОТКРОЙ и внимательно изучи файл `{ctx.explore_file}` — это результаты предварительного исследования по задаче.

        Из него ОБЯЗАТЕЛЬНО используй:
        - Название сервиса используй как домен спеки, не придумывай своё название.
        - Референсные файлы из секции "Референсные файлы" — как архитектурный эталон для проектируемого решения.
        - Конвенции из секции "Конвенции проекта" — спецификация должна им соответствовать.
        - Ключевые находки — что уже есть в проекте и может быть переиспользовано.
        - Открытые вопросы и риски — учти их при проектировании, не игнорируй.

        # Ограничения (MUST)

        - НЕ пиши код реализации — только спецификация.
        - Назови change `{change_name}`, то есть создай его в `openspec/changes/{change_name}/`.
        - Не создавай новый change, если он уже существует для этой задачи.
        - Не проводи исследование заново — оно уже сделано, используй `{ctx.explore_file}`.
        - Не используй ссылки на детали вроде названия методов, ссылок на классы и их свойства
        - Избегай дублирования сценариев. Не нужно расписывать сценарии для перегруженных методов, которые выполняют одно и тоже по смыслу
        - Git-коммит НЕ делай.

        # Требования к спецификации

        - Явно укажи раздел "Не входит в scope" — что сознательно НЕ делается в рамках этой задачи.
        - Разбей работу на конкретные, проверяемые задачи в tasks.md.
        - Каждая задача должна быть достаточно детальной, чтобы её можно было реализовать без дополнительных уточнений.

        # Исходное описание задачи:
        ```
        {ctx.jira.description}
        ```

        # Дополнительно:
        - Номер спринта: `{ctx.jira.sprint}`
        """,
        ctx=ctx,
        change_name=change_name,
    )


