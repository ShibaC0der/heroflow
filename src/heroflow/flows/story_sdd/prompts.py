def fix_spec_comments(ctx: TaskContext, comments_md: str) -> str:
    return render(
        """
        Твоя единственная цель — исправить указанные замечания в файлах спецификации в режиме ПОЛНОЙ АВТОНОМНОСТИ.

        # Замечания на Code Review
        {comments}

        # Предварительно исследование
        Файл с предварительным исследованием `{ctx.explore_file}`

        # Правила выполнения
        1. ИСПРАВЛЕНИЕ ЗАМЕЧАНИЙ: Локализуй места ошибок в файлах папки `{ctx.delta_spec_dir}` и исправь только то, что указано в комментариях.
        2. СТИЛЬ И СТРУКТУРА OpenSpec: Исправленные документы должны идеально соответствовать канонической структуре OpenSpec, быть логичными, технически точными и не содержать "TBD" заглушек.
        3. СИНХРОНИЗАЦИЯ СМЕЖНЫХ ДОКУМЕНТОВ: Если исправление замечания в одном документе (например, в `spec.md`) меняет логику или архитектуру, ты ОБЯЗАН одновременно внести соответствующие правки в остальные локальные файлы спецификации задачи (`design.md`, `tasks.md`, `spec.md`). Все документы спеки должны остаться синхронными.
        4. ЕСЛИ НЕЧЕГО ПРАВИТЬ: Если замечания не требуют изменений в документации или уже исправлены — ничего не меняй.
        5. БЕЗ КОДИНГА И ВОПРОСОВ: Действуй абсолютно автономно, не задавай уточняющих вопросов в чат. Код (production-код приложения) на этом этапе НЕ ПИШИ.
        6. БЕЗ КОММИТОВ: Git-коммит (commit) НЕ ДЕЛАЙ.

        # Валидация
        После внесения изменений обязательно убедись, что:
        - В спецификациях нет синтаксических ошибок Markdown.
        - Пошаговый чек-лист в `tasks.md` полностью соответствует обновленному дизайну и требованиям.
        """,
        ctx=ctx,
        comments=comments_md,
    )


def apply(ctx: TaskContext) -> str:
    return render(
        """
        `/opsx:apply` для {ctx.delta_spec_dir}

        Твоя цель - реализовать изменения в коде на основе артефактов из `{ctx.delta_spec_dir}`, действуя как Senior Developer, который идеально мимикрирует под существующий проект.

        # Правила выполнения:
        1. Исследование референсов: Перед тем как писать новый код, изучи смежные, уже существующие файлы в проекте. Твой новый код должен идеально соответствовать текущей кодовой базе по следующим параметрам:
           - Архитектурные паттерны и структура папок.
           - Стиль написания кода (Code Style, именование переменных, функций, классов).
           - Подходы к обработке ошибок (Error Handling) и логированию.
           - Способы написания тестов и моков.
           Пиши код так, будто его написал автор этого репозитория.
        2. Автономное написание кода: Пошагово выполняй задачи из `tasks.md`. Пиши чистый код с обработкой edge-case'ов.
        3. Обратная синхронизация спеки (Двунаправленность): Если в процессе написания кода или изучения референсов ты поймешь, что заложенная в `design.md` архитектура неоптимальна или противоречит сложившимся практикам проекта - самостоятельно измени код лучшим образом И сразу же перепиши соответствующие пункты в `design.md` и `tasks.md`. Действуй без вопросов.
        4. Цикл самоисправления: После написания кода запускай команду сборки/тестирования проекта. Если линтер или тесты выдают ошибки, автономно исправляй код до тех пор, пока всё не станет зелёным.

        Ограничение: Git-коммит (commit) НЕ ДЕЛАЙ.

        # Дополнительно:
        - Номер спринта: `{ctx.jira.sprint}`
        """,
        ctx=ctx,
    )


